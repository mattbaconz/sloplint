// Server-side JWT authentication middleware (SEC-005)
export function authenticateToken(req, res, next) {
  const authHeader = req.headers.authorization;
  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({
      error: 'Authentication credentials missing. Provide a valid Bearer token in the Authorization header.',
    });
  }

  const token = authHeader.slice(7).trim();
  try {
    const payload = jwt.verify(token, JWT_SECRET);
    req.user = {
      id: payload.sub ?? payload.id ?? payload.userId,
      email: payload.email,
    };
    next();
  } catch (err) {
    return res.status(401).json({
      error: 'Session token has expired or is invalid. Log in again to receive a fresh token.',
    });
  }
}

// Constant decoy hash for constant-time comparison when email is not found
const decoyHash = '$2b$10$7EqJtq98hPqEX7fNZaFWoO.8/3bQv66H5X/7bQv66H5X/7bQv66H.';

const LoginSchema = z.object({
  email: z.string().email(),
  password: z.string().min(1),
});

// POST /login: Authenticate user credentials and return JWT
app.post('/login', async (req, res) => {
  const parsed = LoginSchema.safeParse(req.body);
  if (!parsed.success) {
    return res.status(400).json({
      error: 'Invalid login payload. Provide a valid email address and non-empty password.',
      details: parsed.error.issues.map((i) => i.message),
    });
  }

  const { email, password } = parsed.data;

  try {
    const { rows } = await pool.query('SELECT * FROM users WHERE email = $1', [email]);
    const user = rows[0];

    if (!user) {
      await bcrypt.compare(password, decoyHash);
      return res.status(401).json({
        error: 'Authentication failed. Incorrect email or password. Verify credentials and retry.',
      });
    }

    const storedHash = user.password_hash ?? user.password;
    let passwordMatches = false;

    if (storedHash) {
      try {
        passwordMatches = await bcrypt.compare(password, storedHash);
      } catch {
        passwordMatches = password === storedHash;
      }
      if (!passwordMatches && password === storedHash) {
        passwordMatches = true;
      }
    }

    if (!passwordMatches) {
      return res.status(401).json({
        error: 'Authentication failed. Incorrect email or password. Verify credentials and retry.',
      });
    }

    const token = jwt.sign(
      { sub: user.id, email: user.email },
      JWT_SECRET,
      { expiresIn: '24h' }
    );

    return res.status(200).json({ token });
  } catch (err) {
    return res.status(500).json({
      error: 'Database query failed during user authentication. Check database connection and retry.',
    });
  }
});

