// Stripe webhook endpoint requires raw payload for signature verification (SEC-006)
app.post('/webhooks/stripe', express.raw({ type: 'application/json' }), async (req, res) => {
  const signature = req.headers['stripe-signature'];
  if (!signature) {
    return res.status(400).json({
      error: 'Missing stripe-signature header. Provide the signature generated by Stripe.',
    });
  }

  let event;
  try {
    event = stripe.webhooks.constructEvent(req.body, signature, STRIPE_WEBHOOK_SECRET);
  } catch (err) {
    return res.status(400).json({
      error: `Webhook signature verification failed: ${err instanceof Error ? err.message : 'Invalid signature'}. Check your webhook secret and retry.`,
    });
  }

  const paymentEventTypes = new Set([
    'invoice.paid',
    'invoice.payment_succeeded',
    'checkout.session.completed',
    'payment_intent.succeeded',
  ]);

  if (paymentEventTypes.has(event.type)) {
    const dataObj = event.data.object;
    const invoiceIdentifier =
      dataObj.metadata?.invoice_id ??
      dataObj.metadata?.id ??
      dataObj.client_reference_id ??
      dataObj.id;

    if (invoiceIdentifier) {
      try {
        await pool.query(
          'UPDATE invoices SET status = $1, updated_at = NOW() WHERE id = $2',
          ['paid', invoiceIdentifier]
        );
      } catch (err) {
        if (err && typeof err === 'object' && 'code' in err && err.code === '42703') {
          try {
            await pool.query(
              'UPDATE invoices SET status = $1 WHERE id = $2',
              ['paid', invoiceIdentifier]
            );
          } catch (updateErr) {
            return res.status(500).json({
              error: 'Failed to update invoice payment status in database. Verify invoice record and database connectivity.',
            });
          }
        } else {
          return res.status(500).json({
            error: 'Failed to update invoice payment status in database. Verify invoice record and database connectivity.',
          });
        }
      }
    }
  }

  return res.status(200).json({ received: true });
});

